// @vitest-environment jsdom
import { act, screen, waitFor, within } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import { createLlmFollowUpProvider } from '../adapters/llm-suggestions';
import { createAiSettingsStore } from '../adapters/llm-suggestions/settings-store';
import { FollowUpError } from '../core/follow-up/errors';
import type { FollowUpSuggestion } from '../core/follow-up/blocks';
import type { PartialFollowUp } from '../core/follow-up/partial';
import type { AiModelCatalog, FollowUpContext, FollowUpSuggestionProvider } from '../core/ports';
import { mountApp } from '../test-support/mount';

type Mounted = Awaited<ReturnType<typeof mountApp>>;

const SUGGESTION: FollowUpSuggestion = {
  title: 'Build on your new routine',
  blocks: [
    { type: 'rationale', text: 'A steady evening helps your recovery.' },
    { type: 'new_habit', name: 'Evening wind-down', frequency: 'Daily', timeOfDay: 'Before sleep', durationMinutes: 15 },
    { type: 'metric_target', metric: 'Sleep', target: 7.5, unit: 'h' },
  ],
};

function fakeProvider(
  suggest: FollowUpSuggestionProvider['suggest'],
  configured = true,
): FollowUpSuggestionProvider & { suggest: ReturnType<typeof vi.fn> } {
  return {
    id: 'fake',
    isConfigured: () => configured,
    subscribe: () => () => undefined,
    suggest: vi.fn(suggest),
  };
}

/** A provider whose answer the test settles by hand, so it can look at the app while the request is pending. */
function pendingProvider() {
  const calls: Array<{ signal: AbortSignal | undefined; onPartial?: (p: PartialFollowUp) => void }> = [];
  let settle!: { resolve(s: FollowUpSuggestion): void; reject(e: Error): void };
  const provider = fakeProvider((_ctx, options) => {
    calls.push({ signal: options?.signal, onPartial: options?.onPartial });
    return new Promise<FollowUpSuggestion>((resolve, reject) => {
      settle = { resolve, reject };
    });
  });
  return {
    provider,
    calls,
    resolve: (s: FollowUpSuggestion = SUGGESTION) => act(async () => settle.resolve(s)),
    reject: (e: Error) => act(async () => settle.reject(e)),
  };
}

async function goToComms(m: Mounted) {
  await m.user.click(within(screen.getByRole('navigation', { name: 'Views' })).getByRole('button', { name: /^comms/i }));
}

async function asCmo(m: Mounted) {
  await act(async () => m.actAs('cmo'));
}

async function accept(m: Mounted) {
  await m.user.click((await screen.findAllByRole('button', { name: 'Accept' }))[0]!);
  await waitFor(() => expect(m.state().session!.decisions.at(-1)?.decision).toBe('accepted'));
}

describe('AI follow-up after Accept', () => {
  it('shows a processing modal right after Accept, then turns it into the result without a toast', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    expect(screen.queryByRole('dialog')).toBeNull();
    await accept(m);

    const processing = await screen.findByRole('dialog', { name: 'AI suggestion' });
    expect(processing).toHaveAttribute('aria-modal', 'true');
    expect(processing).toHaveFocus();
    expect(within(processing).getByText(/generating your ai suggestion/i)).toBeInTheDocument();
    expect(within(processing).getAllByRole('button', { name: 'Continue in background' })).toHaveLength(2); // the X and the button

    await p.resolve();
    const dialog = await screen.findByRole('dialog', { name: 'Build on your new routine' });
    expect(within(dialog).getByText('Evening wind-down')).toBeInTheDocument();
    expect(within(dialog).getByText('15 min')).toBeInTheDocument();
    expect(within(dialog).getByText(/7\.5 h/)).toBeInTheDocument();
    expect(within(dialog).getByText(/generated by ai/i)).toBeInTheDocument();
    expect(screen.queryByText('Your AI suggestion is ready')).toBeNull(); // the user was watching

    // The context carries the accepted recommendation and no mood readings.
    const context = p.provider.suggest.mock.calls[0]![0] as FollowUpContext;
    expect(context.accepted.title.length).toBeGreaterThan(0);
    expect(context.findings.length).toBeGreaterThan(0);
    expect(context.readings.some((r) => /mood|phq/i.test(r.indicator))).toBe(false);

    await m.user.click(within(dialog).getByRole('button', { name: 'Dismiss' }));
    expect(screen.queryByRole('dialog')).toBeNull();
  });

  it('renders finished blocks inside the processing modal while the answer streams, never a half block', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    await accept(m);
    const dialog = await screen.findByRole('dialog', { name: 'AI suggestion' });
    expect(within(dialog).queryByLabelText('Suggestion so far')).toBeNull();

    // Only what the adapter reports as finished and valid reaches the modal.
    act(() => p.calls[0]!.onPartial!({ title: 'Build on your new routine', blocks: [SUGGESTION.blocks[0]!] }));
    const so_far = await within(dialog).findByLabelText('Suggestion so far');
    expect(within(so_far).getByText('Build on your new routine')).toBeInTheDocument();
    expect(within(so_far).getByText('A steady evening helps your recovery.')).toBeInTheDocument();
    expect(within(so_far).queryByText('Evening wind-down')).toBeNull();
    expect(within(dialog).getByText(/generating your ai suggestion/i)).toBeInTheDocument(); // still working

    act(() => p.calls[0]!.onPartial!({ title: 'Build on your new routine', blocks: SUGGESTION.blocks }));
    expect(await within(dialog).findByText('Evening wind-down')).toBeInTheDocument();

    await p.resolve();
    expect(await screen.findByRole('dialog', { name: 'Build on your new routine' })).toBeInTheDocument();
  });

  it('keeps the request running after "Continue in background", Escape or the X, and toasts when it is ready', async () => {
    for (const close of ['button', 'escape', 'x'] as const) {
      const p = pendingProvider();
      const m = await mountApp('demo', { followUps: p.provider });
      await accept(m);
      const dialog = await screen.findByRole('dialog', { name: 'AI suggestion' });
      if (close === 'button') await m.user.click(within(dialog).getAllByRole('button', { name: 'Continue in background' })[1]!);
      else if (close === 'escape') await m.user.keyboard('{Escape}');
      else await m.user.click(within(dialog).getAllByRole('button', { name: 'Continue in background' })[0]!);
      expect(screen.queryByRole('dialog')).toBeNull();
      expect(p.calls[0]!.signal?.aborted).toBe(false);

      await p.resolve();
      expect(await screen.findByText('Your AI suggestion is ready')).toBeInTheDocument();
      m.unmount();
    }
  });

  it('survives navigation: toast after the request finishes elsewhere, and View opens the result', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    await accept(m);
    await m.user.keyboard('{Escape}'); // continue in background

    await goToComms(m); // the whole dashboard, zone panel included, unmounts
    expect(screen.queryByRole('list', { name: /^body zones$/i })).toBeNull();
    expect(p.calls[0]!.signal?.aborted).toBe(false);

    await p.resolve();
    expect(await screen.findByText('Your AI suggestion is ready')).toBeInTheDocument();
    expect(screen.queryByRole('dialog')).toBeNull();

    await m.user.click(screen.getByRole('button', { name: 'View' }));
    const dialog = await screen.findByRole('dialog', { name: 'Build on your new routine' });
    expect(within(dialog).getByText('Evening wind-down')).toBeInTheDocument();
    expect(screen.queryByText('Your AI suggestion is ready')).toBeNull(); // the toast closed with its action
    await m.user.click(within(dialog).getByRole('button', { name: 'Dismiss' }));
    expect(screen.queryByRole('dialog')).toBeNull();
  });

  it('survives the app re-hydrating while the request is pending (the panel unmounts)', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    await accept(m);
    await screen.findByRole('dialog', { name: 'AI suggestion' });
    await act(async () => m.store.getState().hydrate());
    expect(p.calls[0]!.signal?.aborted).toBe(false);
    await p.resolve();
    expect(await screen.findByRole('dialog', { name: 'Build on your new routine' })).toBeInTheDocument();
  });

  it('shows a failure toast with a way to the settings when the request fails in the background', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    await accept(m);
    await m.user.keyboard('{Escape}');
    await goToComms(m);
    await p.reject(new FollowUpError('network', 'The AI service could not be reached.'));

    const alert = await screen.findByRole('alert');
    expect(await within(alert).findByText('AI suggestion unavailable: The AI service could not be reached.')).toBeInTheDocument();
    expect(m.state().session!.decisions.at(-1)?.decision).toBe('accepted');
    await m.user.click(within(alert).getByRole('button', { name: 'AI assistant settings' }));
    expect(screen.getByRole('dialog', { name: 'AI assistant' })).toBeInTheDocument();
  });

  it('shows the failure inside the modal when the user is watching, with a link to the settings', async () => {
    const provider = fakeProvider(() => Promise.reject(new FollowUpError('network', 'The AI service could not be reached.')));
    const m = await mountApp('demo', { followUps: provider });
    await accept(m);
    const dialog = await screen.findByRole('dialog', { name: 'AI suggestion' });
    expect(
      await within(dialog).findByText(/AI suggestion unavailable: The AI service could not be reached\. The change you accepted still stands\./),
    ).toBeInTheDocument();
    expect(screen.queryByRole('alert')).toBeNull(); // no duplicate toast
    await m.user.click(within(dialog).getByRole('button', { name: /open ai assistant settings/i }));
    expect(screen.queryByRole('dialog', { name: 'AI suggestion' })).toBeNull();
    expect(screen.getByRole('dialog', { name: 'AI assistant' })).toBeInTheDocument();
  });

  it('aborts a pending request when the signed-in profile changes, and when the app unmounts', async () => {
    const p = pendingProvider();
    const m = await mountApp('demo', { followUps: p.provider });
    await accept(m);
    await m.user.keyboard('{Escape}');
    await asCmo(m);
    expect(p.calls[0]!.signal?.aborted).toBe(true);
    await p.resolve();
    expect(screen.queryByText('Your AI suggestion is ready')).toBeNull();
    expect(screen.queryByRole('dialog')).toBeNull();
    m.unmount();

    const q = pendingProvider();
    const m2 = await mountApp('demo', { followUps: q.provider });
    await accept(m2);
    await screen.findByRole('dialog', { name: 'AI suggestion' });
    m2.unmount();
    expect(q.calls[0]!.signal?.aborted).toBe(true);
  });

  it('sends no request, opens no modal and only hints at setup when the assistant is not configured', async () => {
    const provider = fakeProvider(() => Promise.resolve(SUGGESTION), false);
    const m = await mountApp('demo', { followUps: provider });
    await accept(m);
    expect(await screen.findByRole('button', { name: /set up the ai assistant/i })).toBeInTheDocument();
    expect(screen.queryByRole('dialog')).toBeNull();
    expect(provider.suggest).not.toHaveBeenCalled();
    expect(m.state().session!.decisions.at(-1)?.decision).toBe('accepted');
  });

  it('does not ask for a follow-up on Dismiss', async () => {
    const provider = fakeProvider(() => Promise.resolve(SUGGESTION));
    const m = await mountApp('demo', { followUps: provider });
    await m.user.click((await screen.findAllByRole('button', { name: 'Dismiss' }))[0]!);
    await waitFor(() => expect(m.state().session!.decisions.at(-1)?.decision).toBe('dismissed'));
    expect(provider.suggest).not.toHaveBeenCalled();
    expect(screen.queryByRole('dialog')).toBeNull();
  });

  it('is not offered to roles that cannot accept', async () => {
    await mountApp('demo', { role: 'cmo', followUps: fakeProvider(() => Promise.resolve(SUGGESTION)) });
    expect(screen.queryByRole('button', { name: 'Accept' })).toBeNull();
    expect(screen.queryByRole('dialog')).toBeNull();
  });

  it('regression: Accept from the summary with the real adapter and a saved key opens the modal and calls the service', async () => {
    const aiSettings = createAiSettingsStore({ session: null, local: null });
    aiSettings.set({ apiKey: 'test-key', model: 'gemini-3.8-flash', baseUrl: 'https://example.test/v1/', remember: false });
    const answer = { choices: [{ message: { content: JSON.stringify(SUGGESTION) } }] };
    const fetchMock = vi.fn().mockResolvedValue(new Response(JSON.stringify(answer), { status: 200 }));
    const followUps = createLlmFollowUpProvider({ settings: aiSettings, fetch: fetchMock });
    const m = await mountApp('demo', { followUps, aiSettings });

    // The summary card, with no detail dialog open.
    expect(screen.queryByRole('dialog')).toBeNull();
    await accept(m);
    expect(await screen.findByRole('dialog', { name: 'Build on your new routine' })).toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledTimes(1);
    const [url, init] = fetchMock.mock.calls[0] as [string, RequestInit];
    expect(url).toBe('https://example.test/v1/chat/completions');
    expect(JSON.parse(init.body as string).model).toBe('gemini-3.8-flash');
  });
});

describe('AI assistant settings: insecure base URL warning', () => {
  it('warns for http to a remote host, not for https or loopback', async () => {
    const m = await mountApp('demo', {
      followUps: fakeProvider(() => Promise.resolve(SUGGESTION)),
      aiSettings: createAiSettingsStore({ session: null, local: null }),
    });
    await m.user.click(screen.getByRole('button', { name: /profile menu/i }));
    await m.user.click(screen.getByRole('menuitem', { name: /ai assistant/i }));
    const dialog = screen.getByRole('dialog', { name: 'AI assistant' });
    await m.user.click(within(dialog).getByText('Advanced'));
    const url = within(dialog).getByLabelText('Base URL');
    const warning = () => within(dialog).queryByText(/not encrypted \(http\)/i);
    expect(warning()).toBeNull(); // the default is https
    for (const [value, warns] of [
      ['http://192.168.1.20:11434/v1/', true],
      ['http://example.com/v1/', true],
      ['http://localhost:11434/v1/', false],
      ['http://127.0.0.1:11434/v1/', false],
      ['http://[::1]:11434/v1/', false],
      ['https://example.com/v1/', false],
    ] as const) {
      await m.user.clear(url);
      await m.user.click(url);
      await m.user.paste(value);
      expect(warning() !== null, value).toBe(warns);
    }
  });
});

describe('AI assistant settings: model discovery', () => {
  function catalog(list: AiModelCatalog['listModels']): AiModelCatalog & { listModels: ReturnType<typeof vi.fn> } {
    return { listModels: vi.fn(list), pickDefault: (ids) => ids.find((i) => /flash/.test(i) && !/lite/.test(i)) ?? ids[0] ?? null };
  }

  async function openSettings(m: Mounted) {
    await m.user.click(screen.getByRole('button', { name: /profile menu/i }));
    await m.user.click(screen.getByRole('menuitem', { name: /ai assistant/i }));
    return screen.getByRole('dialog', { name: 'AI assistant' });
  }

  it('tests the connection, lists the models the key can call and picks the newest flash', async () => {
    const aiModels = catalog(() => Promise.resolve(['gemini-4-pro', 'gemini-4-flash', 'gemini-4-flash-lite']));
    const aiSettings = createAiSettingsStore({ session: null, local: null });
    const m = await mountApp('demo', { followUps: fakeProvider(() => Promise.resolve(SUGGESTION)), aiSettings, aiModels });
    const dialog = await openSettings(m);
    const load = within(dialog).getByRole('button', { name: /test connection and load models/i });
    expect(load).toBeDisabled(); // needs a key first
    await m.user.type(within(dialog).getByLabelText('API key'), 'my-key');
    await m.user.click(load);

    expect(await within(dialog).findByText('Connected. 3 models available.')).toBeInTheDocument();
    expect(aiModels.listModels).toHaveBeenCalledWith({ apiKey: 'my-key', baseUrl: aiSettings.presets.defaultBaseUrl });
    const select = within(dialog).getByLabelText('Model');
    expect(within(select).getAllByRole('option').map((o) => o.textContent)).toEqual([
      'gemini-4-pro',
      'gemini-4-flash',
      'gemini-4-flash-lite',
      'Custom model...',
    ]);
    expect(select).toHaveValue('gemini-4-flash'); // the preset default is not callable with this key
  });

  it('keeps the presets and shows the reason when listing fails', async () => {
    const aiModels = catalog(() => Promise.reject(new FollowUpError('http', 'The AI service rejected this API key.')));
    const m = await mountApp('demo', { followUps: fakeProvider(() => Promise.resolve(SUGGESTION)), aiSettings: createAiSettingsStore({ session: null, local: null }), aiModels });
    const dialog = await openSettings(m);
    await m.user.type(within(dialog).getByLabelText('API key'), 'bad');
    await m.user.click(within(dialog).getByRole('button', { name: /test connection and load models/i }));
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('The AI service rejected this API key.');
    expect(within(within(dialog).getByLabelText('Model')).getAllByRole('option').map((o) => o.textContent)).toEqual([
      'gemini-3.8-flash',
      'gemini-3.5-flash-lite',
      'Custom model...',
    ]);
  });
});

describe('AI assistant settings', () => {
  it('lets the astronaut save a key from the hint, through the real adapter', async () => {
    const aiSettings = createAiSettingsStore({ session: null, local: null });
    const fetchMock = vi.fn();
    const followUps = createLlmFollowUpProvider({ settings: aiSettings, fetch: fetchMock });
    const m = await mountApp('demo', { followUps, aiSettings });
    await accept(m);
    expect(fetchMock).not.toHaveBeenCalled();

    await m.user.click(await screen.findByRole('button', { name: /set up the ai assistant/i }));
    const dialog = screen.getByRole('dialog', { name: 'AI assistant' });
    const key = within(dialog).getByLabelText('API key');
    expect(key).toHaveAttribute('type', 'password');
    expect(within(dialog).getByLabelText('Model')).toHaveValue('gemini-3.8-flash');
    expect(within(dialog).getByLabelText('Remember on this device')).not.toBeChecked();
    await m.user.type(key, 'my-key');
    await m.user.click(within(dialog).getByRole('button', { name: 'Save' }));
    expect(aiSettings.get().apiKey).toBe('my-key');
    expect(aiSettings.isConfigured()).toBe(true);

    await m.user.click(screen.getByRole('button', { name: /profile menu/i }));
    await m.user.click(screen.getByRole('menuitem', { name: /ai assistant/i }));
    await m.user.click(within(screen.getByRole('dialog', { name: 'AI assistant' })).getByRole('button', { name: /forget key/i }));
    expect(aiSettings.isConfigured()).toBe(false);
  });
});
