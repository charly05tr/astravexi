import { HEALTH_SIM_PARAMS, SIM_INDICATORS } from '../adapters/health-sim';
import type { SimParam } from '../adapters/health-sim';
import { CATALOG } from './scenario-instance';
import type { PredictedColumn, Rate } from './run-evaluation';
import { PREDICTED_COLUMNS, TRUTH_CLASSES } from './run-evaluation';
import type { EvalResults } from './results';

const pct = (r: Rate): string => (r.rate === null ? 'n/a' : `${(r.rate * 100).toFixed(1)}%`);
const ci = (r: Rate): string => (r.ci95 ? `${(r.ci95.lo * 100).toFixed(1)}-${(r.ci95.hi * 100).toFixed(1)}%` : 'n/a');
const frac = (r: Rate): string => `${r.k}/${r.n}`;
const row = (cells: ReadonlyArray<string | number>): string => `| ${cells.join(' | ')} |`;
const table = (head: string[], rows: ReadonlyArray<ReadonlyArray<string | number>>): string =>
  [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');

function paramRows(): string[][] {
  const out: string[][] = [];
  const add = (indicator: string, name: string, p: SimParam) =>
    out.push([indicator, name, String(p.value), p.assumption ? 'ASSUMPTION' : 'sourced', p.source ?? 'none (design choice)']);
  for (const [name, p] of Object.entries(HEALTH_SIM_PARAMS.global)) add('global', name, p);
  for (const id of SIM_INDICATORS) {
    const ind = HEALTH_SIM_PARAMS.indicators[id];
    add(id, 'baselineMean', ind.baselineMean);
    add(id, 'baselineBetweenSd', ind.baselineBetweenSd);
    add(id, 'withinSd', ind.withinSd);
    add(id, 'ar1', ind.ar1);
    add(id, 'measurementSd', ind.measurementSd);
    if (ind.circadian) for (const [name, p] of Object.entries(ind.circadian)) add(id, `circadian.${name}`, p);
  }
  return out;
}

/** The human-readable report. Everything numeric comes from `results`, so it can never disagree with results.json. */
export function renderSummary(r: EvalResults): string {
  const s = r.summary;
  const t = s.totals;
  const cell = (truth: (typeof TRUTH_CLASSES)[number], col: PredictedColumn) => s.confusion[truth][col];
  const anomalyTypes = s.byType.filter((b) => b.anomalies > 0);
  const control = s.falseAlarms.noAnomalyType;
  const sharedRow = s.byTruthClass.find((b) => b.truth === 'shared')!;
  const lowBucket = s.byMagnitude[0]!;
  const sharedWrong = cell('shared', 'individual');

  return `# Attribution engine evaluation

Generated ${r.generatedOn}. Reproduce with \`pnpm eval:engine\`; verified by \`src/eval/engine-eval.test.ts\`.

## Result

> ${r.sentence}

- Attribution among all injected anomalies (undetected count as wrong): ${frac(t.attributionAmongInjected)} (${pct(t.attributionAmongInjected)}, 95% Wilson ${ci(t.attributionAmongInjected)}).
- Detection: ${frac(t.detected)} = ${pct(t.detected)} (95% Wilson ${ci(t.detected)}).
- Attribution among detected anomalies: ${frac(t.attributionAmongDetected)} = ${pct(t.attributionAmongDetected)} (95% Wilson ${ci(t.attributionAmongDetected)}).
- False alarms: ${t.falseAlarms} findings that match no injected anomaly, ${t.falseAlarmsPer100CrewDays} per 100 crew-days (${t.judgedCrewDays} judged crew-days in total). In the no-anomaly control alone: ${control.total} in ${control.scenarios} scenarios, ${control.per100CrewDays} per 100 crew-days; ${control.scenariosWithAtLeastOne} of ${control.scenarios} control scenarios had at least one false alarm.
- The ${t.scenarios} scenarios are ${CATALOG.scenarioTypes.length} scenario types x ${r.seeds.length} seeds (${r.seeds[0]}..${r.seeds[r.seeds.length - 1]}); ${t.scenarios - control.scenarios} of them contain injected anomalies.

## Honesty caveats (read before quoting the number)

- **The data is synthetic and generated by our own simulator.** The numbers verify the engine's logic under the simulator's assumptions. They are not clinical validity, not a field trial and not a performance claim about real astronauts.
- The engine is a statistical attribution engine (robust z-scores against each person's own 28-day baseline, a crew co-occurrence rule and documented cabin links). It is not a trained ML model and the report never calls it one.
- The engine, its thresholds and the knowledge in \`src/knowledge/cabin.json\` were not modified and not tuned. The scenario catalog (SHA-256 \`${r.scenarioFileSha256}\`) was declared before the first run. Simulator parameters (SHA-256 \`${r.healthSimParamsSha256}\`) were fixed before the first run.
- Most simulator spreads (between-person SD, day-to-day SD, AR(1), measurement noise) are explicit design assumptions, see "Simulator parameters". The false-alarm rate and the detection rate of small effects depend directly on them.
- Anomaly magnitude is the mean shift in units of the person's own day-to-day SD. The reading of that day still carries its own noise, so a 5 SD shift can produce a reading that looks like 3 SD.
- The Wilson intervals treat anomalies as independent, but anomalies of one scenario share a crew, a cabin and an episode (cabin-heat-crew has 6 per scenario), so the intervals are optimistic. The false-alarm counts of the 7 scenario types are not independent either: every seed gives the same crew and the same noise in all types, so the injected episode is the only difference between types (a paired design).
- Only readings from mission day ${CATALOG.firstDay + CATALOG.warmupDays} on are judged (${CATALOG.judgedDays} days per scenario, after a ${CATALOG.warmupDays}-day warm-up of normal days that feeds the baselines). The false-alarm rate is therefore the rate with mature baselines, not during the first weeks.
- Each person has one block of 7 readings per day (the app's morning schedule); the engine judges every indicator every day, including PHQ-2 and both blood pressures, which the injected anomalies never touch.

## Frozen definitions

- **Anomaly unit** = one (person, indicator, episode). An environmental event that hits 3 crew is 3 anomalies.
- **Episode**: ${CATALOG.durationDays.min}-${CATALOG.durationDays.max} consecutive mission days. Start = start of the first affected day, end = end of the last affected day.
- **Detected**: the engine produces at least one finding for that person and indicator whose reading time is inside [episode start, episode end + the largest documented lag for that indicator in cabin.json]. Lags: heart rate and temperature 360 min, sleep 720 min, indicators with no link 0.
- **False alarm**: any finding (one atypical reading) that does not match an injected anomaly. Counted per reading, as the app shows them. Reported as a count, per 100 crew-days, and separately for the no-anomaly control.
- **Verdict to class**: likely-internal -> individual; likely-external -> environmental; possibly-external whose reason is a linked excursion (individual susceptibility, or crew unknown) -> environmental; possibly-external whose reason is crew-wide with no monitored excursion -> shared; insufficient-data -> undetermined (counts as incorrect). Every VerdictReason is mapped in \`REASON_CLASS\` (src/eval/scenario-instance.ts): crew-wide-environment-unknown does not fit any rule above exactly and is mapped to shared (crew moved together, no monitored excursion); it occurred ${s.findingsByReason['crew-wide-environment-unknown'] ?? 0} times because the simulator always supplies cabin data. insufficient-baseline, insufficient-crew-data and no-environment-data map to undetermined and occurred 0 times among findings (findings only exist for readings with a baseline).
- **Several matching findings**: the anomaly's class is the majority class; ties go to the earliest finding.
- **Attribution correctness**: Z of K with K = detected anomalies, and Z' of M with M = all injected anomalies (undetected counted as wrong).
- **Intervals**: 95% Wilson score intervals.

## Scenario catalog

${table(
  ['Type', 'Cabin excursion', 'Injected anomalies (ground truth)', 'Description'],
  CATALOG.scenarioTypes.map((x) => [
    x.id,
    x.cabinExcursion ? `${x.cabinExcursion.variable} +${x.cabinExcursion.deltaRange[0]}..${x.cabinExcursion.deltaRange[1]}` : 'none (nominal)',
    x.anomalies.length === 0 ? 'none' : x.anomalies.map((a) => `${a.indicatorId} ${a.direction}, ${a.affected} crew, ${a.class}`).join('; '),
    x.description,
  ]),
)}

Crew of ${CATALOG.crewSize}. Magnitude uniform ${CATALOG.magnitudeSd.min}-${CATALOG.magnitudeSd.max} SD per anomaly. Onset uniform in judged days ${CATALOG.onsetOffsetDays.min}-${CATALOG.onsetOffsetDays.max}. The cabin is the calibrated nominal cabin of \`cabin-timeline.ts\` (with its nominal clamp inside the NASA limits); excursions exist only where a scenario says so.

## Results by scenario type

${table(
  ['Type', 'Scenarios', 'Anomalies', 'Detected', 'Detection (95% CI)', 'False alarms', 'FA per 100 crew-days', 'Correct attribution (of detected)', 'Correct (of injected)'],
  s.byType.map((b) => [
    b.typeId,
    b.scenarios,
    b.anomalies,
    b.anomalies ? frac(b.detected) : 'n/a',
    b.anomalies ? `${pct(b.detected)} (${ci(b.detected)})` : 'n/a',
    b.falseAlarms,
    b.falseAlarmsPer100CrewDays ?? 'n/a',
    b.anomalies ? `${frac(b.attributionAmongDetected)} (${pct(b.attributionAmongDetected)})` : 'n/a',
    b.anomalies ? `${frac(b.attributionAmongInjected)}` : 'n/a',
  ]),
)}

Attribution accuracy of detected anomalies by type, with 95% Wilson intervals: ${anomalyTypes
    .map((b) => `${b.typeId} ${pct(b.attributionAmongDetected)} (${ci(b.attributionAmongDetected)})`)
    .join('; ')}.

## Detection by magnitude

${table(
  ['Magnitude', 'Anomalies', 'Detected', 'Detection (95% CI)', 'Correct attribution (of detected)', 'Correct (of injected)'],
  s.byMagnitude.map((b) => [b.bucket, b.anomalies, frac(b.detected), `${pct(b.detected)} (${ci(b.detected)})`, `${frac(b.attributionAmongDetected)} (${pct(b.attributionAmongDetected)})`, frac(b.attributionAmongInjected)]),
)}

## Confusion matrix (ground truth x engine class)

${table(
  ['Truth \\ Engine', ...PREDICTED_COLUMNS, 'Total'],
  TRUTH_CLASSES.map((c) => [c, ...PREDICTED_COLUMNS.map((p) => cell(c, p)), PREDICTED_COLUMNS.reduce((n, p) => n + cell(c, p), 0)]),
)}

"missed" = not detected. By ground-truth class:

${table(
  ['Truth class', 'Anomalies', 'Detection (95% CI)', 'Correct (of detected)', 'Correct (of injected)'],
  s.byTruthClass.map((b) => [b.truth, b.anomalies, `${frac(b.detected)} ${pct(b.detected)} (${ci(b.detected)})`, `${frac(b.attributionAmongDetected)} ${pct(b.attributionAmongDetected)} (${ci(b.attributionAmongDetected)})`, frac(b.attributionAmongInjected)]),
)}

## False alarms

Total ${s.falseAlarms.total} (${s.falseAlarms.per100CrewDays} per 100 crew-days). By indicator: ${Object.entries(s.falseAlarms.byIndicator)
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}. By engine reason: ${Object.entries(s.falseAlarms.byReason)
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}.

Almost every false alarm is an isolated atypical reading with no cabin or crew signal, labelled "likely internal". That is the expected cost of a |robust z| >= 3 threshold applied to 7 indicators x 3 people every day with a 28-reading baseline, on integer-quantised readings (PHQ-2, heart rate and blood pressure are whole numbers, so the robust scale is small).

## Where the engine fails, and why

1. **Small effects are missed (rule: outlierZ = 3).** Detection is ${pct(lowBucket.detected)} for effects of 2-3 SD against ${pct(s.byMagnitude[3]!.detected)} for 5-6 SD. A reading can only become a finding when its robust z reaches 3; a mean shift of 2-3 SD reaches it only on a favourable noise draw. A few larger effects are missed too because the day's noise pulls the reading back toward the baseline.
2. **Crew-wide shared causes are often called individual (rule: crew co-occurrence, crewFraction 0.5 with crewMinOthers 2).** Shared accuracy among detected is ${pct(sharedRow.attributionAmongDetected)} (${frac(sharedRow.attributionAmongDetected)}); ${sharedWrong} shared anomalies were labelled individual (reason no-external-signal). With a crew of 3 each person has only 2 peers, and \`needed = max(2, ceil(0.5 x 2)) = 2\`: BOTH peers must deviate by |z| >= 2 in the same direction within 12 h. If one crewmate's effect is small or lost in noise, the other two see a single deviating peer, the crew call becomes "individual", and with the cabin nominal the verdict is "likely internal". In the committed run, every one of these scenarios also contains a weak, undetected crewmate (checked by hand on results.json). This is the pending crew-wide rule discussion; the rule was NOT changed here.
3. **Environmental attribution is robust here for a structural reason.** A linked excursion yields an environmental verdict regardless of the crew call (likely-external when the crew moved too, possibly-external with individual susceptibility otherwise), so a weak crewmate does not flip it. This also means the engine cannot tell the heat scenario's "whole crew" from "one susceptible person" apart: the verdict class is the same.
4. **The confounder is handled correctly.** Glucose has no documented cabin link, so \`assessEnvironmentLink\` returns no-documented-link and the heat excursion is not blamed. The residual error there is detection misses, not mis-attribution.
5. **Scope limits of this test.** The test injects mean shifts on one to two indicators per episode. It does not test slow drifts, anomalies in several indicators at once, two overlapping events, a crew larger than 3, or a person whose baseline is itself contaminated by an earlier anomaly.

## Simulator parameters (sources versus assumptions)

Source file: \`src/knowledge/health-sim-params.json\`. "sourced" means the file names a reference for the value; none of the external references was re-fetched while building this evaluation (\`citationChecked\` is false in the file), so re-verify them before quoting. Anything marked ASSUMPTION is a design choice with no source.

${table(['Indicator', 'Parameter', 'Value', 'Status', 'Source'], paramRows())}

The cabin comes from \`src/adapters/seeded-history/cabin-timeline.ts\`, calibrated on NASA OSDR EDA telemetry (\`src/knowledge/cabin-calibration.json\`); no parameters were added.

## Reproduce

\`\`\`
pnpm eval:engine        # rewrites reports/engine-eval/results.json and summary.md (about 10 s)
pnpm eval:engine -- --check   # full re-run of all ${t.scenarios} scenarios in memory; exits non-zero if results.json differs (about 10 s)
pnpm test                     # src/eval/engine-eval.test.ts re-runs a deterministic subset (first 6 seeds of every type, 42 scenarios) and checks the committed aggregates and sentence against the committed records
\`\`\`

Attribution config used: ${JSON.stringify(r.attributionConfig)}
`;
}
